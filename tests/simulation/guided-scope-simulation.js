const fs=require('fs');
const vm=require('vm');
const path=require('path');
const P=require('../../js/engines/planner-engine.js');
const root=path.resolve(__dirname,'../..');
const ctx={window:{}}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root,'data/curriculum/2022/curriculum.js'),'utf8'),ctx);
const data=ctx.window.CURRILOOP_CURRICULUM_DATA;
const guided=P.buildStudySections(data,['middle-info'],'과목 공통');
if(!guided.length) throw new Error('guided scope empty');
if(guided.some(x=>x.subjectKey!=='middle-info')) throw new Error('guided scope leaked non-middle subject');
const areas=[...new Set(guided.filter(x=>x.area!=='과목 공통').map(x=>x.area))];
if(areas.length!==5) throw new Error(`middle-info areas ${areas.length}`);
let state=P.normalizeState({completedSectionIds:guided.map(x=>x.id)});
if(P.progressSummary(guided,state).percent!==100) throw new Error('guided scope should be 100%');
if(P.createNextSession(guided,state,0,Date.now())!==null) throw new Error('guided scope must stop after middle-info completion');
const full=P.buildStudySections(data,['middle-info','high-info','ai-basic','data-science','software-life','info-science'],'과목 공통');
if(!full.some(x=>x.subjectKey==='high-info')) throw new Error('full corpus probe missing high-info');
console.log(JSON.stringify({guidedSections:guided.length,areas,fullSections:full.length,stopsAt100:true},null,2));
