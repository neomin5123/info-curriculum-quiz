'use strict';
const fs=require('fs'); const vm=require('vm'); const path=require('path');
const root=path.resolve(__dirname,'..');
const ctx={window:{}}; vm.createContext(ctx);
for (const file of ['data/curriculum-data.js','data/supplemental-data.js','data/practice-bank.js']) vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx,{filename:file});
const data=ctx.window.CURRILOOP_CURRICULUM_DATA;
const bank=ctx.window.CURRILOOP_PRACTICE_BANK;
if (!bank || !Array.isArray(bank.questions) || bank.questions.length!==100) throw new Error('practice bank must contain 100 questions');
const ids=new Set(); const sourceIds=new Set();
for (const subject of Object.values(data)) for (const groups of Object.values(subject)) for (const sections of Object.values(groups)) if (Array.isArray(sections)) for (const section of sections) for (const line of section.lines||[]) sourceIds.add(line.id);
let compare=0,ready=0; const areas=new Set();
for (const q of bank.questions) {
  if(ids.has(q.questionId)) throw new Error(`duplicate question ${q.questionId}`); ids.add(q.questionId);
  if(!q.tasks?.length || q.tasks.length!==q.answerUnits?.length) throw new Error(`task/answer mismatch ${q.questionId}`);
  if(q.comparison2015) compare++; else ready++;
  areas.add(`${q.subject}|${q.area}`);
  for(const sid of q.sourceIds||[]) if(!sourceIds.has(sid)) throw new Error(`unknown source ${q.questionId}: ${sid}`);
  const total=(q.tasks||[]).reduce((s,t)=>s+Number(t.points||0),0);
  const expected=q.examStyle==='2점형'?2:4;
  if(total!==expected) throw new Error(`points mismatch ${q.questionId}: ${total}`);
}
if(compare!==6 || ready!==94) throw new Error(`version mix ${ready}/${compare}`);
const expectedAreas=27;
const regularAreas=[...areas].filter(x=>!x.endsWith('|과목 공통'));
if(new Set(regularAreas).size!==expectedAreas) throw new Error(`regular area coverage ${new Set(regularAreas).size}`);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
for(const marker of ['id="practiceTab"','id="practicePage"','id="practiceSubject"','id="practicePattern"','id="practiceDifficulty"','id="practiceVersion"','id="practiceQuestionArea"']) if(!html.includes(marker)) throw new Error(`practice UI missing ${marker}`);
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
for(const marker of ['practice: document.getElementById("practicePage")','window.CurriLoopPracticeUI?.onShow?.()','["general","subject","practice","history"]']) if(!app.includes(marker)) throw new Error(`app practice integration missing ${marker}`);
const sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
for(const marker of ['/data/practice-bank.js?v=6.11.1','/js/practice-engine.js?v=6.11.1','/js/practice-ui.js?v=6.11.1']) if(!sw.includes(marker)) throw new Error(`SW practice cache missing ${marker}`);
console.log(`v6.10 practice regression QA: OK (${bank.questions.length} questions, 2022=${ready}, comparison=${compare}, areas=${new Set(regularAreas).size})`);
