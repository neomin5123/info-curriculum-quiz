import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const sha=s=>crypto.createHash('sha256').update(s).digest('hex');
const d=JSON.parse(fs.readFileSync('data/exams/major-exams-2014-2026.json','utf8'));
const audit=JSON.parse(fs.readFileSync('data/audits/2026-10-22-build-02-third-pass-2017-pedagogy.json','utf8'));
const ids=['2017-A-01','2017-A-02','2017-A-03','2017-A-09','2017-A-10','2017-B-01','2017-B-08'];
assert.equal(audit.metadata.buildId,'2026.10.22-02');
assert.equal(audit.metadata.baselineBuildId,'2026.10.22-01');
assert.equal(d.questions.length,269);
assert.equal(d.questions.filter(q=>q.solutionStatus==='solved').length,268);
assert.equal(d.questions.filter(q=>q.solutionStatus==='pending').length,1);
assert.equal(d.questions.find(q=>q.id==='2024-B-07')?.solutionStatus,'pending');
assert.deepEqual(audit.entries.map(x=>x.id),ids);
assert.equal(Object.keys(audit.baselineAnswerSha256).length,268);
for(const q of d.questions.filter(q=>q.solutionStatus==='solved')) assert.equal(sha(q.answer),audit.baselineAnswerSha256[q.id],'stored answer changed: '+q.id);
for(const e of audit.entries){
 const q=d.questions.find(q=>q.id===e.id);
 assert(q && q.subject==='교교론');
 assert.equal(sha(q.answer),e.storedAnswerSha256);
 assert.equal(sha(q.solution),e.storedSolutionSha256);
 assert.equal(e.officialAnswerConfirmed,false);
 assert.equal(e.independentExactExamAnswerCompared,false);
 assert.equal(e.answerEdited,false);
 assert.equal(e.appSolutionEdited,false);
 assert.deepEqual(e.sourcePages,q.source.pages);
 assert.equal(e.questionImageCount,q.images.length);
 assert(e.workedExplanation.length>200 && e.limitations.length>40);
 assert.equal(e.validationLevels.originalExam,'direct-match-to-user-provided-PDF-and-atlas');
 assert.equal(e.validationLevels.officialAnswerKey,'not-found-not-compared');
 assert.equal(e.validationLevels.executableCheck,'not-applicable');
 for(const s of e.externalSources) assert(s.url.startsWith('https://') && s.class && s.supports);
}
assert.equal(audit.entries.reduce((n,e)=>n+e.points,0),28);
assert.deepEqual(audit.independentExecutableChecks.notApplicableIds,ids);
assert.equal(audit.metadata.cumulativeThirdPassQuestions,18);
assert.equal(audit.metadata.officialAnswerConfirmed,0);
assert.equal(audit.metadata.independentExactExamAnswerCompared,0);
assert.equal(audit.reviewLevelSummary.storedAnswerChanged,0);
assert.equal(audit.reviewLevelSummary.storedAppExplanationChanged,0);
console.log(JSON.stringify({status:'PASS',examCount:269,unchangedStoredAnswers:268,thirdPass2017:7,points:28,cumulativeThirdPass:18,officialKeyCompared:0,externalExactCompared:0,executable:'N/A'}));
